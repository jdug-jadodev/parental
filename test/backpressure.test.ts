import assert from 'node:assert/strict';
import { sign } from 'node:crypto';
import { once } from 'node:events';
import { createServer } from 'node:http';
import type { AddressInfo } from 'node:net';
import { test } from 'node:test';
import { AutenticarConexion } from '../src/application/usecase/autenticar-conexion.usecase.js';
import { EvaluarConexion } from '../src/application/usecase/evaluar-conexion.usecase.js';
import { ProcesarMensaje } from '../src/application/usecase/procesar-mensaje.usecase.js';
import { Configuracion } from '../src/domain/entities/configuracion.js';
import { RetosAutenticacionAdapter } from '../src/infrastructure/adapter/retos-autenticacion.adapter.js';
import { RelojAdapter } from '../src/infrastructure/adapter/reloj.adapter.js';
import { EntropiaAdapter } from '../src/infrastructure/adapter/entropia.adapter.js';
import { VerificacionAutenticacionAdapter } from '../src/infrastructure/adapter/verificacion-autenticacion.adapter.js';
import { VerificacionMensajeAdapter } from '../src/infrastructure/adapter/verificacion-mensaje.adapter.js';
import { WebSocketAdapter } from '../src/infrastructure/adapter/websocket.adapter.js';
import { bytesFirma } from '../src/infrastructure/adapter/protocol/crypto-protocol.js';
import { crearTransporteWebSocket } from '../src/infrastructure/config/websocket.config.js';
import { ClienteAuth, codecAuth, entornoAuth, firmarAuth } from './soporte/cliente-auth.js';

test('R-LIMIT-02: backpressure simulado en socket real cierra receptor y notifica al emisor', async (contexto) => {
  const { env, claves, pareja } = entornoAuth();
  const config = new Configuracion(10000, env.PUBLIC_ORIGIN, pareja, env.PARENT_PUBLIC_KEY_B64, env.CHILD_PUBLIC_KEY_B64, 'test', 'error');
  const transporte = crearTransporteWebSocket();
  const auth = new AutenticarConexion(pareja, new RetosAutenticacionAdapter(), new RelojAdapter(), new EntropiaAdapter(), new VerificacionAutenticacionAdapter(codecAuth, config));
  const adapter = new WebSocketAdapter(new EvaluarConexion(true), auth, transporte, new ProcesarMensaje(new VerificacionMensajeAdapter(codecAuth, config)));
  const servidor = createServer();
  servidor.on('upgrade', (solicitud, socket, head) => adapter.upgrade(solicitud, socket, head));
  servidor.listen(0, '127.0.0.1');
  await once(servidor, 'listening');
  contexto.after(async () => {
    adapter.detener();
    const cerrado = once(servidor, 'close');
    servidor.close();
    await cerrado;
  });
  const url = `ws://127.0.0.1:${(servidor.address() as AddressInfo).port}/ws`;
  const padre = await ClienteAuth.conectar(url);
  padre.enviar(firmarAuth(await padre.reto(), pareja, 'PARENT', claves.PARENT.privateKey));
  await padre.recibir();
  const hijo = await ClienteAuth.conectar(url);
  hijo.enviar(firmarAuth(await hijo.reto(), pareja, 'CHILD', claves.CHILD.privateKey));
  await hijo.recibir();
  const receptor = [...transporte.clients][1]!;
  Object.defineProperty(receptor, 'bufferedAmount', { get: () => 65537 });
  const payload = codecAuth.codificarPayload({ v: 1, kind: 'SYNC_REQUEST', pairId: pareja, sender: 'PARENT', syncNonce: new EntropiaAdapter().nonce() });
  const sigB64 = sign('sha256', bytesFirma('MESSAGE', payload), { key: claves.PARENT.privateKey, dsaEncoding: 'der' }).toString('base64url');
  padre.enviar(codecAuth.codificarFrame({ v: 1, kind: 'SIGNED', purpose: 'MESSAGE', payloadB64: payload.toString('base64url'), sigB64 }));
  assert.deepEqual(await padre.recibir(), { v: 1, kind: 'PEER_UNAVAILABLE', reason: 'PEER_OFFLINE', refCommandId: null });
  assert.equal(await hijo.cerrado, 1008);
  assert.equal(padre.socket.readyState, 1);
  await assert.rejects(padre.recibir(100), /Timeout/);
});
